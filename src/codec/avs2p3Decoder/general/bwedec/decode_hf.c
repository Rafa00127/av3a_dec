/*******************************************************************************
Functionname:  CalculateEnergyPerBlockDec
*******************************************************************************
\brief   Calculate the energy of each block.			

\return  the energy of each block, including the reference energy 
		and estimation energy.
*******************************************************************************/
static void CalculateEnergyPerBlockDec(const float *bwe_psd,
									   const float *ref_energy_sfb,
									   float *ref_energy_block,
									   float *est_energy_block,
									   int adHarmonicVec[],
									   SFB_PARAM sfbParam)
{
	int sfb, li, ui, b, i;
	int count;

	float estEnergy;

	int blockLen = sfbParam.blockLen;
	int blockNum = sfbParam.blockNum;
	int k = 0;
	
	for (sfb = 0; sfb < sfbParam.sfbCnt; sfb++)
	{
		li = sfbParam.sfbOffset[sfb];
		ui = sfbParam.sfbOffset[sfb + 1];

		estEnergy = 0.0f;
		for (i = li * blockLen; i < ui * blockLen; i++)
		{
			estEnergy += bwe_psd[i];
		}

		count = (ui - li) * blockLen;
		for (b = li; b < ui; b++)
		{
			est_energy_block[b] = estEnergy / (float)count;
			ref_energy_block[b] = ref_energy_sfb[sfb];
		}

	}
}



/***************************************************************************/
/*
  \brief     Decodes one huffman code word

  \return    decoded value
****************************************************************************/
static int
DecodeHuffman (Huffman h,
			   avs2audiopack_buffer* opb)
{
  char index = 0;
  int value, bit;

  while (index >= 0) {

    bit = avs2audiopack_read(opb, 1);

    index = h[index][bit];
  }

  value = index+64;

  return value;
}


void GetBWEParameters(BWEBITSTREAM *pStream, StDecoderHFPrmData *param, SFB_PARAM sfbParam)
{
	int i, sfb;
	int tmp;
	int groupMode, seqMode, groupNum;
	int blockNum;
	int (*BlockTabletmp)[16];
	int (*GroupTabletmp)[10];
	int onsetFlag, onsetPos;
	int timeFlag;
	Huffman huff;
	int envelop_index, noisefloor_index;
	avs2audiopack_buffer opb;


	for(i = 0; i < pStream->NrElements; i++)
	{
		memset(&opb,0,sizeof(avs2audiopack_buffer));
		opb.buffer = opb.ptr = pStream->bweElement[i].Data;
		opb.storage = pStream->bweElement[i].Payload;
		opb.endbit = 0;
		opb.endbyte = 0;

		//get grouping information
		tmp = avs2audiopack_read(&opb, 1);
		if(tmp == 0)
			groupMode = 0;
		else
			groupMode = 4;

		if(groupMode == 0)
			seqMode = avs2audiopack_read(&opb, 4);
		else
			seqMode = avs2audiopack_read(&opb, 10);
		
		param[0].groupMode = groupMode;
		param[0].seqMode = seqMode;


		BlockTabletmp = (int(*)[16])getBlockseqTable(groupMode);
		blockNum = BlockTabletmp[seqMode][1];

		GroupTabletmp = (int(*)[10])getGroupseqTable(groupMode);
		groupNum = GroupTabletmp[seqMode][1];

		//get transient information
		onsetFlag = avs2audiopack_read(&opb, 1);
		if(onsetFlag)
			onsetPos = avs2audiopack_read(&opb, 4);
		else
			onsetPos = GroupTabletmp[seqMode][3];
		
		param[0].onsetFlag = onsetFlag;
		param[0].onsetPos = onsetPos;

		//get BWE data information
		//get envelop information
		timeFlag = avs2audiopack_read(&opb, 1);
		if(timeFlag)
		{
			huff = book_envelop_time_Decode;

			for(sfb = 0; sfb < sfbParam.sfbCnt; sfb++)
			{
				param[0].hf_env[sfb] = avs2audiopack_read(&opb, 5);
				for(i = 1; i < groupNum; i++)
				{
					envelop_index =  DecodeHuffman(huff, &opb);
					param[i].hf_env[sfb] = param[i-1].hf_env[sfb] + envelop_index;
				}
			}
		}
		else
		{
			huff = book_envelop_freq_Decode;

			for(i = 0; i < groupNum; i++)
			{
				param[i].hf_env[0] = avs2audiopack_read(&opb, 5);
				for(sfb = 1; sfb < sfbParam.sfbCnt; sfb++)
				{
					envelop_index = DecodeHuffman(huff, &opb);
					param[i].hf_env[sfb] = param[i].hf_env[sfb-1] + envelop_index;
				}
			}			
		}

		//get noise floor information
		if(groupNum > 1)
		{
			timeFlag = avs2audiopack_read(&opb, 1);

			if(timeFlag)
			{
				huff = book_noisefloor_time_Decode;

				for(sfb = 0; sfb < sfbParam.sfbCntNoiseFloor; sfb++)
				{
					param[0].noise_floor[sfb] = avs2audiopack_read(&opb, 4) + NOISE_FLOOR_OFFSET - 1;
					for(i = 1; i < 2; i++)
					{
						noisefloor_index =  DecodeHuffman(huff, &opb);
						param[i].noise_floor[sfb] = param[i-1].noise_floor[sfb] + noisefloor_index;
					}
				}
			}
			else
			{
				huff = book_noisefloor_freq_Decode;

				for(i = 0; i < 2; i++)
				{
					param[i].noise_floor[0] = avs2audiopack_read(&opb, 4) + NOISE_FLOOR_OFFSET - 1;
					for(sfb = 1; sfb < sfbParam.sfbCntNoiseFloor; sfb++)
					{
						noisefloor_index = DecodeHuffman(huff, &opb);
						param[i].noise_floor[sfb] = param[i].noise_floor[sfb-1] + noisefloor_index;
					}
				}
			}
		}
		else
		{
			huff = book_noisefloor_freq_Decode;

			param[0].noise_floor[0] = avs2audiopack_read(&opb, 4) + NOISE_FLOOR_OFFSET - 1;
			for(sfb = 1; sfb < sfbParam.sfbCntNoiseFloor; sfb++)
			{
				noisefloor_index = DecodeHuffman(huff, &opb);
				param[0].noise_floor[sfb] = param[0].noise_floor[sfb-1] + noisefloor_index;
			}
		}
		
		//get BWE extended information
		param[0].addHarmonicFlag = avs2audiopack_read(&opb, 1);

		if(param[0].addHarmonicFlag)
		{	
			for(i = 0; i < sfbParam.sfbCnt; i++)
				param[0].addHarmonicVec[i] = avs2audiopack_read(&opb, 1);
		}
		else
		{
			for(i = 0; i < sfbParam.sfbCnt; i++)
				param[0].addHarmonicVec[i] = 0;
		}

	}

	return;
}

int Avs2BweDecoderOpen(unsigned int *st_in, int bitrate, int sampleRateCore, int numChannels, int *bandWidth,int *config_idx)
{
	int idx=0;
	int i, paramSets = sizeof (tuningTable) / sizeof (tuningTable [0]);

	for (i = 0 ; i < paramSets ; i++)
	{
		if (numChannels == tuningTable [i].numChannels) 
		{
			if ((sampleRateCore == tuningTable [i].sampleRate) && (bitrate >= tuningTable [i].bitrateFrom) &&
					(bitrate < tuningTable [i].bitrateTo)) 
				idx = i;
		}
	}

	*bandWidth = tuningTable[idx].startFreq  * 32;
	*config_idx = idx;
	
	*st_in = (unsigned int *) (malloc(sizeof(StAvs2BweDecode)));

	memset((void*)*st_in, 0, sizeof(StAvs2BweDecode));
	
	return 0;
}


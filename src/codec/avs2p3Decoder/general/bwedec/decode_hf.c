/*!
  \brief  Calculate gain, noise, and additional sine level for one block.
*/
void CalculateBlockGain(float  nrgRef,
                            float  nrgEst,
                            float  tmpNoise,
                            float  *ptrNrgGain,
                            float  *ptrNoiseLevel,
                            float  *ptrNrgSine,
                            int   sinePresentFlag,
                            int   sineMapped,
                            int    noNoiseFlag,int count)
{
  float a,b;
  float c;

  nrgEst += 1.0f;

  a = nrgRef * tmpNoise;

  b = 1.0f + tmpNoise;

  *ptrNoiseLevel = 0.0001/*0.1*/* a / b; //lijing added 0.01

  if (sinePresentFlag) {

    c = b * nrgEst;

    *ptrNrgGain = a / c;
#if HARMNIC_MODE
    if (sineMapped) {
		*ptrNrgSine = nrgRef / b * count;
    }
#else
	if (sineMapped) {
		*ptrNrgSine = nrgRef / b;
	}
#endif
  }
  else {
    if (noNoiseFlag) {
      b = nrgEst;
    }
    else {
      b = b * nrgEst;
    }

    *ptrNrgGain = nrgRef / b;
  }

}

/*!
  \brief  Calculate "average gain" for the specified sfb range.
*/
void calcAvgGain(float  *nrgRef,
                        float  *nrgEst,
                        int    lowSubband,
                        int    highSubband,
                        float  *ptrSumRef,
                        float  *ptrAvgGain)
{
  float sumRef = 1.0;
  float sumEst = 1.0;
  int    k;

  for (k=lowSubband; k<highSubband; k++){

    sumRef += nrgRef[k];

    sumEst += nrgEst[k];
  }

  *ptrAvgGain = sumRef / sumEst;

  *ptrSumRef = sumRef;

}

